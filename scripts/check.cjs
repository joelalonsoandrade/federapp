const {chromium, webkit} = require('playwright');
const {PDFDocument} = require('pdf-lib');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const output = path.resolve(__dirname,'../output/playwright');
async function check(browserType, label) {
  const browser = await browserType.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1365,height:1080},deviceScaleFactor:1,acceptDownloads:true});
  const page = await context.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:4173');
  await page.locator('#save-status').filter({hasText:'bereit'}).waitFor();
  await page.locator('#sample-text').click();
  await page.locator('#missing-note').filter({hasText:'Beispielschrift'}).waitFor();
  await page.screenshot({path:path.join(output,`${label}-studio.png`),fullPage:true,animations:'disabled'});
  await page.locator('[data-view="alphabet"]').click();
  const box=await page.locator('#draw-canvas').boundingBox();
  const at=(x,y)=>[box.x+x*box.width/600,box.y+y*box.height/360];
  await page.mouse.move(...at(250,150));await page.mouse.down();
  for(const [x,y] of [[230,160],[210,190],[220,225],[250,240],[280,215],[275,155],[275,240],[295,240]])await page.mouse.move(...at(x,y),{steps:4});
  await page.mouse.up();await page.locator('#save-glyph').click();
  await page.locator('#variant-count').filter({hasText:'1'}).waitFor();
  await page.locator('#save-status').filter({hasText:'Auf diesem Gerät gespeichert'}).waitFor();
  await page.reload();await page.locator('#save-status').filter({hasText:'geladen'}).waitFor();
  await page.locator('[data-view="alphabet"]').click();
  assert.equal(await page.locator('#variant-count').textContent(),'1','saved glyph survives reload');
  assert.equal(await page.locator('#text').inputValue(), await page.evaluate(()=>SAMPLE),'text survives reload');
  await page.screenshot({path:path.join(output,`${label}-alphabet.png`),fullPage:true,animations:'disabled'});
  const backupDownload=page.waitForEvent('download');await page.locator('#backup-export').click();
  const backup=await backupDownload,backupPath=path.join(output,`${label}-backup.json`);await backup.saveAs(backupPath);
  const backupData=JSON.parse(await fs.readFile(backupPath,'utf8'));assert.equal(backupData.glyphs.a.length,1);
  // Verify a second real variant, random selection and restoring the complete workspace.
  const box2=await page.locator('#draw-canvas').boundingBox();
  await page.mouse.move(box2.x+box2.width*.4,box2.y+box2.height*.45);await page.mouse.down();
  await page.mouse.move(box2.x+box2.width*.55,box2.y+box2.height*.67,{steps:8});await page.mouse.up();
  await page.locator('#save-glyph').click();await page.locator('#variant-count').filter({hasText:'2'}).waitFor();
  await page.evaluate(()=>{state.text='a'.repeat(50);renderPreview();});
  assert.equal(await page.evaluate(()=>new Set(pages.flat().map(g=>state.glyphs.a.indexOf(g.v))).size),2,'both variants randomly selected');
  page.once('dialog',d=>d.accept());await page.locator('#backup-file').setInputFiles(backupPath);
  await page.locator('#variant-count').filter({hasText:'1'}).waitFor();
  await page.locator('[data-view="studio"]').click();
  await page.locator('#text').fill('a '.repeat(1600)+'\nÄÖÜ äöü ß 0123456789!?');
  await page.locator('#text').dispatchEvent('input');
  await page.waitForFunction(()=>pages.length>1);
  const pageTotal=await page.evaluate(()=>pages.length);
  const stable=await page.evaluate(()=>JSON.stringify(pages));
  await page.locator('#next-page').click();await page.locator('#prev-page').click();
  assert.equal(await page.evaluate(()=>JSON.stringify(layout())),stable,'layout has stable seed');
  await page.locator('#export-open').click();
  const pdfDownload=page.waitForEvent('download');await page.locator('#download-pdf').click();
  const pdf=await pdfDownload;const pdfPath=path.join(output,`${label}-notes.pdf`);await pdf.saveAs(pdfPath);
  const doc=await PDFDocument.load(await fs.readFile(pdfPath));
  assert.equal(doc.getPageCount(),pageTotal,'all pages exported');
  assert.equal(Math.round(doc.getPage(0).getWidth()),596,'A4 dimensions');
  await page.locator('#transparent').check();
  const pngDownload=page.waitForEvent('download');await page.locator('#download-png').click();
  const png=await pngDownload;await png.saveAs(path.join(output,`${label}-transparent.png`));
  const {PNG}=require('pngjs');
  const pngData=PNG.sync.read(await fs.readFile(path.join(output,`${label}-transparent.png`)));
  assert.equal(pngData.data[3],0,'PNG background is actually transparent');
  assert.ok(pngData.data.some((v,i)=>i%4===3 && v>0),'PNG contains ink');
  await page.locator('#export-dialog .close-dialog').click();
  await page.locator('[data-paper="grid"]').click();await page.locator('#format').selectOption('a5');
  await page.waitForFunction(()=>pageCanvas.getAttribute('viewBox')==='0 0 559 794');
  await page.locator('#reset-settings').click();
  assert.equal(await page.evaluate(()=>state.glyphs.a.length),1,'reset preserves alphabet');
  // Import a real image file and verify the paper survives a reload.
  const paper= new PNG({width:32,height:48});paper.data.fill(255);
  const templatePath=path.join(output,`${label}-template.png`);await fs.writeFile(templatePath,PNG.sync.write(paper));
  await page.locator('#template-file').setInputFiles(templatePath);
  await page.locator('#custom-template').waitFor({state:'visible'});
  await page.locator('#save-status').filter({hasText:'Auf diesem Gerät gespeichert'}).waitFor();await page.reload();
  await page.locator('#custom-template').waitFor({state:'visible'});
  assert.ok(await page.evaluate(()=>templateImage?.width>0),'template survives reload');
  await page.locator('#remove-template').click();
  await page.setViewportSize({width:1024,height:768});
  await page.locator('#text').fill('Meine Notizen auf dem iPad.\nEine zweite Zeile.');
  await page.screenshot({path:path.join(output,`${label}-ipad.png`),fullPage:true,animations:'disabled'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'iPad no horizontal overflow');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,`${label}-mobile.png`),fullPage:true,animations:'disabled'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile no horizontal overflow');
  // Closing and reopening a tab must also restore the local database.
  await page.locator('#save-status').filter({hasText:'Auf diesem Gerät gespeichert'}).waitFor();
  await page.close();const reopened=await context.newPage();await reopened.goto('http://127.0.0.1:4173');
  await reopened.locator('#save-status').filter({hasText:'geladen'}).waitFor();
  assert.equal(await reopened.evaluate(()=>state.glyphs.a.length),1,'glyph survives closed tab');
  assert.equal(errors.length,0,errors.join('\n'));
  console.log(`${label}: reload, closed tab, multiple variants, backup restore, template import, stable random layout, ${pageTotal}-page PDF, transparent PNG, reset, responsive layout passed; no runtime errors.`);
  await browser.close();
}
(async()=>{await fs.mkdir(output,{recursive:true});await check(chromium,'chromium');try{await check(webkit,'webkit');}catch(error){if(/Executable doesn't exist/.test(error.message))console.log('WebKit not installed; Chromium coverage completed.');else throw error;}})().catch(error=>{console.error(error);process.exit(1);});
